#include <iostream>

using namespace std;

int main() {
    setlocale(LC_ALL, "Ukrainian");
    
    cout << "--- ЗАДАЧА Begin20: Переведення градусів у радіани ---" << endl;
    
    double degrees, radians;
    const double PI = 3.14; // За умовою завдання константа pi приймається рівною 3.14

    // Введення значення кута в градусах
    cout << "Введіть значення кута в градусах: ";
    cin >> degrees;

    // Формула переведення: радіани = (градуси * pi) / 180
    radians = (degrees * PI) / 180.0;

    // Виведення результату обчислення
    cout << "Результат: Кут становить " << radians << " радіан." << endl;

    return 0;
}
